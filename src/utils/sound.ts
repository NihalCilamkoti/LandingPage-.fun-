// Procedural Web Audio API Sound Synthesizer for EnthiosHub Playhouse
// Lightweight, offline, zero external audio asset dependencies, with persistent mute toggle.

let audioCtx: AudioContext | null = null;
let isMutedState = false;

if (typeof window !== 'undefined') {
  try {
    isMutedState = localStorage.getItem('enthios_playhouse_muted') === 'true';
  } catch {
    isMutedState = false;
  }
}

function getAudioContext(): AudioContext | null {
  if (isMutedState) return null;
  if (typeof window === 'undefined') return null;

  if (!audioCtx) {
    const AudioContextClass =
      window.AudioContext ||
      (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }

  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume();
  }

  return audioCtx;
}

export function isSoundMuted(): boolean {
  return isMutedState;
}

export function toggleSoundMute(): boolean {
  isMutedState = !isMutedState;
  try {
    localStorage.setItem('enthios_playhouse_muted', String(isMutedState));
  } catch {}
  return isMutedState;
}

// 1. Gentle UI Click / Pop
export function playClickSound() {
  const ctx = getAudioContext();
  if (!ctx) return;
  try {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(440, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(880, ctx.currentTime + 0.05);

    gain.gain.setValueAtTime(0.12, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.05);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.05);
  } catch {}
}

